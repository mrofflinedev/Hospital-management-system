@login_required
def manage_appointment_labs(request, appointment_id):
    if request.user.role not in [User.Role.ADMIN, User.Role.DOCTOR] and not request.user.is_superuser:
        return redirect('dashboard_redirect')

    appointment = get_object_or_404(Appointment, id=appointment_id)
    lab_requests = appointment.lab_requests.all().order_by('-requested_at')

    if request.method == 'POST':
        action = request.POST.get('action')
        if action == 'request_test':
            req_form = LabRequestForm(request.POST)
            if req_form.is_valid():
                lab_req = req_form.save(commit=False)
                lab_req.appointment = appointment
                lab_req.save()
                messages.success(request, f'Requested {lab_req.test.name}.')
                return redirect('manage_appointment_labs', appointment_id=appointment.id)
        elif action == 'submit_result':
            req_id = request.POST.get('lab_request_id')
            lab_req = get_object_or_404(LabRequest, id=req_id, appointment=appointment)
            result_notes = request.POST.get('result_notes', '').strip()
            if result_notes:
                lab_req.result_notes = result_notes
                lab_req.status = LabRequest.Status.COMPLETED
                lab_req.completed_at = timezone.now()
                lab_req.save()
                messages.success(request, f'Results saved for {lab_req.test.name}.')
                return redirect('manage_appointment_labs', appointment_id=appointment.id)

    return render(request, 'hospital/manage_labs.html', {
        'appointment': appointment,
        'lab_requests': lab_requests,
        'req_form': LabRequestForm(),
    })
