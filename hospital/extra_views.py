from django.shortcuts import render, redirect, get_object_or_404
from django.contrib.auth.decorators import login_required
from django.contrib import messages
from django.utils import timezone
from accounts.models import User
from .models import Appointment, Bill, Medicine, LabTest, LabRequest
from .forms import (
    AdminInvoiceForm,
    MedicineForm,
    DispenseMedicineForm,
    LabTestCatalogForm,
    LabRequestForm,
)


@login_required
def admin_create_invoice(request, appointment_id=None):
    if request.user.role != User.Role.ADMIN and not request.user.is_superuser:
        return redirect('dashboard_redirect')

    unbilled_list = Appointment.objects.filter(bill__isnull=True)
    appointment = get_object_or_404(Appointment, id=appointment_id) if appointment_id else None

    if appointment and hasattr(appointment, 'bill'):
        messages.info(request, 'An invoice already exists for this appointment.')
        return redirect('print_invoice', bill_id=appointment.bill.id)

    if request.method == 'POST':
        selected_id = request.POST.get('appointment_id') or appointment_id
        appointment = get_object_or_404(Appointment, id=selected_id)
        form = AdminInvoiceForm(request.POST)
        if form.is_valid():
            bill = form.save(commit=False)
            bill.appointment = appointment
            bill.save()
            messages.success(request, f'Invoice #AHC-{bill.id:04d} generated by Admin.')
            return redirect('print_invoice', bill_id=bill.id)
    else:
        if appointment:
            pharmacy_total = sum(i.subtotal for i in appointment.dispensed_medicines.all())
            lab_total = sum(r.test.cost for r in appointment.lab_requests.all())
            form = AdminInvoiceForm(initial={
                'consultation_fee': appointment.doctor.consultation_fee,
                'medication_charges': pharmacy_total + lab_total,
            })
        else:
            form = AdminInvoiceForm()

    return render(request, 'hospital/admin_create_invoice.html', {
        'form': form,
        'appointment': appointment,
        'unbilled_list': unbilled_list,
    })


@login_required
def print_invoice(request, bill_id):
    bill = get_object_or_404(Bill, id=bill_id)
    appointment = bill.appointment

    is_owner = (request.user.role == User.Role.PATIENT and appointment.patient.user == request.user)
    is_doctor = (request.user.role == User.Role.DOCTOR and appointment.doctor.user == request.user)
    is_admin = (request.user.role == User.Role.ADMIN or request.user.is_superuser)

    if not (is_owner or is_doctor or is_admin):
        messages.error(request, 'You are not authorized to view this invoice.')
        return redirect('dashboard_redirect')

    dispensed_items = appointment.dispensed_medicines.all()
    lab_requests = appointment.lab_requests.all()
    pharmacy_total = sum(item.subtotal for item in dispensed_items)
    lab_total = sum(req.test.cost for req in lab_requests)
    other_med_charges = bill.medication_charges - (pharmacy_total + lab_total)

    return render(request, 'hospital/invoice_print.html', {
        'bill': bill,
        'appointment': appointment,
        'dispensed_items': dispensed_items,
        'lab_requests': lab_requests,
        'other_med_charges': other_med_charges if other_med_charges > 0 else 0,
        'stamp_date': timezone.now(),
    })


@login_required
def pharmacy_inventory(request):
    if request.user.role not in [User.Role.ADMIN, User.Role.DOCTOR] and not request.user.is_superuser:
        return redirect('dashboard_redirect')

    medicines = Medicine.objects.all()
    if request.method == 'POST':
        if request.user.role != User.Role.ADMIN and not request.user.is_superuser:
            messages.error(request, 'Only Hospital Administrators can add medicines.')
            return redirect('pharmacy_inventory')
        form = MedicineForm(request.POST)
        if form.is_valid():
            form.save()
            messages.success(request, 'Medicine added to inventory.')
            return redirect('pharmacy_inventory')
    else:
        form = MedicineForm()

    return render(request, 'hospital/pharmacy_inventory.html', {'medicines': medicines, 'form': form})


@login_required
def restock_medicine(request, medicine_id):
    if request.user.role != User.Role.ADMIN and not request.user.is_superuser:
        return redirect('dashboard_redirect')

    medicine = get_object_or_404(Medicine, id=medicine_id)
    if request.method == 'POST':
        added_qty = int(request.POST.get('added_qty', 0))
        if added_qty > 0:
            medicine.stock_quantity += added_qty
            medicine.save()
            messages.success(request, f'Added {added_qty} units to {medicine.name}.')
    return redirect('pharmacy_inventory')


@login_required
def dispense_medicine(request, appointment_id):
    if request.user.role not in [User.Role.ADMIN, User.Role.DOCTOR] and not request.user.is_superuser:
        return redirect('dashboard_redirect')

    appointment = get_object_or_404(Appointment, id=appointment_id)
    dispensed_items = appointment.dispensed_medicines.all()

    if request.method == 'POST':
        form = DispenseMedicineForm(request.POST)
        if form.is_valid():
            item = form.save(commit=False)
            item.appointment = appointment
            item.save()

            med = item.medicine
            med.stock_quantity -= item.quantity
            med.save()

            if hasattr(appointment, 'bill'):
                bill = appointment.bill
                bill.medication_charges += item.subtotal
                bill.save()

            messages.success(request, f'Dispensed {item.quantity}x {med.name}.')
            return redirect('dispense_medicine', appointment_id=appointment.id)
    else:
        form = DispenseMedicineForm()

    return render(request, 'hospital/dispense_medicine.html', {
        'appointment': appointment,
        'dispensed_items': dispensed_items,
        'form': form,
    })


